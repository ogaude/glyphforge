"""Hand-built pyarrow Parquet writer with the Hugging Face ``huggingface`` schema metadata.

One COLUMNS table drives both the pyarrow schema and the HF feature metadata, so they cannot drift. ``datasets`` is never imported
here: the metadata entry alone makes ``load_dataset("parquet", ...)`` recognise the Image feature. Output has no timestamps; byte
identity of two writes holds per pyarrow version (the footer records ``created_by``), which the export manifest records.
"""

from __future__ import annotations

import json
from collections.abc import Iterable
from pathlib import Path

import pyarrow as pa
import pyarrow.parquet as pq

from glyphforge.sources.base import LICENSES

COLUMNS: tuple[tuple[str, str], ...] = tuple(sorted({
    **dict.fromkeys(
        ("bitmap_sha256", "class_version", "control_glyph", "control_kind", "degrade_ops", "env", "error_class", "family", "font",
         "generator_version", "image_digest", "image_sha256", "label", "pair_id", "paper_id", "paper_version", "recipe_sha256", "role",
         "rules", "sample_id", "site_level", "source", "source_canon", "structure", "style", "style_preamble_sha256", "wrapper",
         "license", "license_uri", "attribution", "arxiv_id"), "string"),
    **dict.fromkeys(("attempt", "n_sites", "n_tokens", "pad_px", "size_pt", "slot"), "int64"),
    **dict.fromkeys(("width", "height"), "int32"),
    "seed": "uint64", "column_cm": "float64", "authors": "list_string", "flags": "list_string", "image": "image",
}.items()))
_PA = {"string": pa.string(), "int64": pa.int64(), "int32": pa.int32(), "uint64": pa.uint64(), "float64": pa.float64(),
       "list_string": pa.list_(pa.string()), "image": pa.struct([("bytes", pa.binary()), ("path", pa.string())])}  # fmt: skip
_HF_STR = {"dtype": "string", "_type": "Value"}
_HF = {"image": {"_type": "Image"}, "list_string": {"feature": _HF_STR, "_type": "List"}, "string": _HF_STR,
       **{k: {"dtype": k, "_type": "Value"} for k in ("int64", "int32", "uint64", "float64")}}  # fmt: skip
CC0_STATEMENT = f"Synthetic sample generated by GlyphForge; dedicated to the public domain under CC0-1.0 ({LICENSES['CC0-1.0']})"
MODIFIED = "modified: synthetic glyph substitutions, re-rendered by GlyphForge"
_SCHEMA = pa.schema(
    [(name, _PA[kind]) for name, kind in COLUMNS],
    metadata={"huggingface": json.dumps({"info": {"features": {n: _HF[k] for n, k in COLUMNS}}}, sort_keys=True)},
)


def hf_features() -> dict:
    return {name: _HF[kind] for name, kind in COLUMNS}


def parquet_row(s: dict, png: bytes, ops: list[dict]) -> dict:
    by = s["licence"].startswith("CC-BY")
    version = s["paper_version"] or ""
    version = version if version.startswith("v") or not version else "v" + version
    attribution = (
        f"arXiv:{s['paper_id']}{version}, {', '.join(s['authors'])}; {s['licence']} ({LICENSES[s['licence']]}); {MODIFIED}" if by else CC0_STATEMENT
    )
    row = {k: v for k, v in s.items() if k not in ("image", "licence", "rules")}
    row.update(
        image={"bytes": png, "path": None}, license=s["licence"], license_uri=LICENSES[s["licence"]], attribution=attribution,
        arxiv_id=s["paper_id"] if by else None, degrade_ops=json.dumps(ops, sort_keys=True), rules=json.dumps(s["rules"], sort_keys=True),
    )  # fmt: skip
    return row


def write_parquet(out_dir: Path, rows: Iterable[dict], *, shard_bytes: int, row_group_rows: int) -> list[str]:
    data = Path(out_dir) / "data"
    data.mkdir(parents=True, exist_ok=True)
    tmp: list[Path] = []
    writer: pq.ParquetWriter | None = None
    batch: list[dict] = []
    size = 0

    def flush() -> None:
        nonlocal batch
        if batch:
            assert writer is not None  # a row is batched only after the shard writer opened
            writer.write_table(pa.Table.from_pylist(batch, schema=_SCHEMA))
            batch = []

    def close() -> None:
        nonlocal writer, size
        flush()
        assert writer is not None  # close runs only for an open shard
        writer.close()
        writer, size = None, 0

    for row in rows:
        if writer is None:
            tmp.append(data / f".shard-{len(tmp):05d}.parquet")
            writer = pq.ParquetWriter(tmp[-1], _SCHEMA, compression="zstd", use_dictionary=False)
        batch.append(row)
        size += len(row["image"]["bytes"])
        if len(batch) >= row_group_rows:
            flush()
        if size >= shard_bytes:
            close()
    if writer is not None:
        close()
    if not tmp:
        tmp.append(data / ".shard-00000.parquet")
        pq.ParquetWriter(tmp[0], _SCHEMA, compression="zstd", use_dictionary=False).close()
    names = [f"data/train-{i:05d}-of-{len(tmp):05d}.parquet" for i in range(len(tmp))]
    for src, name in zip(tmp, names, strict=True):
        src.replace(Path(out_dir) / name)
    return names
